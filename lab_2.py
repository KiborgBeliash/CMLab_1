def thomas_algorithm(a, b, c, d):
    """
    Метод прогонки для трехдиагональной системы
    a - нижняя диагональ
    b - главная диагональ
    c - верхняя диагональ
    d - вектор правых частей
    """
    n = len(b)
    
    alpha = [0] * n
    beta = [0] * n
    
    # Прямой ход первое
    alpha[0] = -c[0] / b[0]
    beta[0] = d[0] / b[0]
    
    # Остальные уравнения остальные
    for i in range(1, n):
        denom = b[i] + a[i] * alpha[i-1]
        alpha[i] = -c[i] / denom
        beta[i] = (d[i] - a[i] * beta[i-1]) / denom
    
    # Обратный ход
    x = [0] * n
    x[n-1] = beta[n-1]
    
    for i in range(n-2, -1, -1):
        x[i] = alpha[i] * x[i+1] + beta[i]
    
    return x

# Задаем коэффициенты системы
# Нижняя диагональ
a = [0, -1, -9, -1, 9]

# Главная диагональ
b = [-6, 13, -15, -7, -18]

# Верхняя диагональ
c = [5, 6, -4, 1, 0]

# Вектор правых частей
d = [51, 100, -12, 47, -90]

x = thomas_algorithm(a, b, c, d)

print("Решение системы:")
for i, xi in enumerate(x, 1):
    print(f"x{i} = {xi:.6f}")

